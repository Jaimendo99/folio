let language = "en";
function setLanguage(choice, systemLocale) {
  language = choice === "es" || (choice === "system" && /^es(?:[-_]|$)/i.test(systemLocale)) ? "es" : "en";
}
function t(key, values = {}) {
  return (language === "es" ? es[key] : en[key]).replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}
